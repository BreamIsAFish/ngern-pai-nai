import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-09-20T12:00:00.000Z'))
})

test('edits an expense into a transfer in place and updates Ledger and Summary totals', async ({ page }) => {
  await page.goto('/')
  await page.addStyleTag({ content: '.vc-switch, #__vconsole { display: none !important; }' })
  await expect(page.locator('.ledger-row')).toHaveCount(4)
  await expect(page.locator('.month-total > strong')).toHaveText('฿185')
  await page.getByRole('button', { name: /Food Lunch with May/ }).click()

  const form = page.locator('.transaction-screen')
  await expect(form.locator('.entry-header')).toContainText('Edit entry')
  await expect(form.locator('.entry-tabs > button')).toHaveCount(3)
  await expect(form.locator('.entry-tabs')).toHaveCSS('border-radius', '999px')
  await form.getByRole('button', { name: 'Transfer', exact: true }).click()
  await expect(form.getByRole('button', { name: 'Choose category' })).toBeHidden()
  await expect(form.getByLabel('Destination')).toHaveValue('')
  await form.getByLabel('Destination').fill('Savings account')
  await expect(form.getByLabel('Amount')).toHaveValue('120')
  await page.screenshot({ path: 'test-results/edit-transfer.png' })
  await form.getByRole('button', { name: 'Save', exact: true }).click()

  const changed = page.locator('.ledger-row').filter({ hasText: 'Lunch with May' })
  await expect(form).toBeHidden()
  await expect(changed).toHaveCount(1)
  await expect(changed).toHaveClass('ledger-row transfer')
  await expect(changed).toHaveAttribute('data-category', 'Transfer')
  await expect(changed).toContainText('Savings account')
  await expect(page.locator('.ledger-row')).toHaveCount(4)
  await expect(page.locator('.month-total > strong')).toHaveText('฿65')
  await expect(page.locator('.month-other-totals')).toHaveText('Income +48,000Transferred 1,120')
  await expect(page.getByLabel('Daily totals').first()).toContainText('Expenses65and 2 transfers')

  await page.getByRole('button', { name: 'Summary', exact: true }).click()
  await expect(page.getByRole('img', { name: 'expense total 65', exact: true })).toBeVisible()
  await page.locator('.summary-tabs').getByRole('button', { name: 'transfer', exact: true }).click()
  await expect(page.getByRole('img', { name: 'transfer total 1,120', exact: true })).toBeVisible()
  await expect(page.locator('.chart-legend')).toContainText('2 transfer entries')

  // Reload the month's data through the bridge to verify the persisted result too.
  await page.getByRole('button', { name: 'Home', exact: true }).click()
  await page.getByRole('button', { name: 'Previous month' }).first().click()
  await expect(page.getByRole('status')).toBeHidden()
  await page.getByRole('button', { name: 'Next month' }).first().click()
  await expect(page.getByRole('status')).toBeHidden()
  await expect(page.locator('.ledger-row')).toHaveCount(4)
  await expect(changed).toHaveCount(1)
  await expect(changed).toHaveClass('ledger-row transfer')
  await expect(page.locator('.month-total > strong')).toHaveText('฿65')
  await changed.click()
  await expect(form.getByLabel('Destination')).toHaveValue('Savings account')
  await form.getByRole('button', { name: 'Expense', exact: true }).click()
  await expect(form.getByLabel('Destination')).toBeHidden()
  await expect(form.getByRole('button', { name: 'Choose category', exact: true })).toBeVisible()
  await form.getByRole('button', { name: 'Food', exact: true }).click()
  await form.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(changed).toHaveClass('ledger-row expense')
  await expect(changed).not.toContainText('Savings account')
  await expect(page.locator('.ledger-row')).toHaveCount(4)
  await expect(page.locator('.month-total > strong')).toHaveText('฿185')
})

test('unlocks the type of a saved receipt and clears its merchant before entering a transfer destination', async ({ page }) => {
  await page.goto('/')
  await page.addStyleTag({ content: '.vc-switch, #__vconsole { display: none !important; }' })
  await page.getByRole('button', { name: 'Scan receipt' }).click()
  await page.getByRole('button', { name: /เลือกจากคลังรูปภาพ/ }).click()
  const results = page.getByRole('dialog', { name: 'ผลการสแกนใบเสร็จ' })
  await expect(results.getByText(/เพิ่มแล้ว 2/)).toBeVisible()
  await results.getByRole('button', { name: 'เสร็จสิ้น' }).click()
  const receipt = page.locator('.ledger-row').filter({ hasText: 'ร้านตัวอย่าง' }).filter({ hasText: '245' })
  await receipt.click()
  const form = page.locator('.transaction-screen')
  await expect(form.getByRole('button', { name: 'Income', exact: true })).toBeEnabled()
  await expect(form.getByRole('button', { name: 'Transfer', exact: true })).toBeEnabled()
  await form.getByRole('button', { name: 'Transfer', exact: true }).click()
  await expect(form.getByPlaceholder('ชื่อร้าน')).toBeHidden()
  await expect(form.getByLabel('Destination')).toHaveValue('')
  await expect(form.getByPlaceholder('เลขที่รายการ')).toHaveValue('TX-receipt-1')
  await form.getByLabel('Destination').fill('Receipt savings')
  await form.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.locator('.ledger-row.transfer').filter({ hasText: 'Receipt savings' })).toHaveCount(1)
  await expect(page.locator('.ledger-row')).toHaveCount(6)
  await expect(page.locator('.month-total > strong')).toHaveText('฿274')
  await expect(page.locator('.month-other-totals')).toContainText('Transferred 1,245')
})
